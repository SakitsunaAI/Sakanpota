pub fn glyph_row(ch: char, row: usize) -> u8 {
    let code = ch as usize;
    if !(0x20..=0x7F).contains(&code) || row >= 8 {
        return 0;
    }
    FONT_8X8[code - 0x20][row]
}

pub fn draw_char(buf: &mut [u32], x: i32, y: i32, ch: char, color: u32) {
    for row in 0..8 {
        let py = y + row as i32;
        if py < 0 || py >= CANVAS_HEIGHT as i32 {
            continue;
        }
        let bits = glyph_row(ch, row);
        for col in 0..8 {
            if (bits & (0x80 >> col)) != 0 {
                let px = x + col;
                if px >= 0 && px < CANVAS_WIDTH as i32 {
                    buf[py as usize * CANVAS_WIDTH + px as usize] = color;
                }
            }
        }
    }
}

pub fn draw_string(buf: &mut [u32], x: i32, y: i32, text: &str, color: u32) {
    let mut cx = x;
    for ch in text.chars() {
        draw_char(buf, cx, y, ch, color);
        cx += 8;
        if cx >= CANVAS_WIDTH as i32 {
            break;
        }
    }
}

pub fn fill_rect(buf: &mut [u32], x: i32, y: i32, w: i32, h: i32, color: u32) {
    let x0 = x.max(0);
    let y0 = y.max(0);
    let x1 = (x + w).min(CANVAS_WIDTH as i32);
    let y1 = (y + h).min(CANVAS_HEIGHT as i32);
    if x0 >= x1 || y0 >= y1 {
        return;
    }
    for py in y0..y1 {
        let row_start = py as usize * CANVAS_WIDTH;
        for px in x0..x1 {
            buf[row_start + px as usize] = color;
        }
    }
}

pub fn draw_rect_outline(buf: &mut [u32], x: i32, y: i32, w: i32, h: i32, color: u32) {
    if w <= 0 || h <= 0 {
        return;
    }
    fill_rect(buf, x, y, w, 1, color);
    fill_rect(buf, x, y + h - 1, w, 1, color);
    fill_rect(buf, x, y, 1, h, color);
    fill_rect(buf, x + w - 1, y, 1, h, color);
}

/// Blits an arbitrary native RGB/ARGB framebuffer scaled cleanly onto the 640x512 canvas.
#[allow(clippy::too_many_arguments)]
pub fn blit_scaled(
    src: &[u32],
    src_w: usize,
    src_h: usize,
    dst: &mut [u32],
    dst_x: usize,
    dst_y: usize,
    dst_w: usize,
    dst_h: usize,
) {
    if src_w == 0 || src_h == 0 || dst_w == 0 || dst_h == 0 {
        return;
    }
    for dy in 0..dst_h {
        let out_y = dst_y + dy;
        if out_y >= CANVAS_HEIGHT {
            break;
        }
        let sy = dy * src_h / dst_h;
        let src_row = sy * src_w;
        let dst_row = out_y * CANVAS_WIDTH;
        for dx in 0..dst_w {
            let out_x = dst_x + dx;
            if out_x >= CANVAS_WIDTH {
                break;
            }
            let sx = dx * src_w / dst_w;
            dst[dst_row + out_x] = src[src_row + sx];
        }
    }
}

/// Renders the real-time LLE debugger overlay directly using live CPU, disassembly, RAM, and audio reads.
#[allow(clippy::too_many_arguments)]
pub fn render_debugger_overlay(
    buf: &mut [u32],
    sys_name: &str,
    media_name: &str,
    paused: bool,
    cpu: &CpuDebugState,
    disasm: &[DisassembledInstruction],
    mem_base: u32,
    mem_bytes: &[u8],
    audio_samples: &[i16],
) {
    // Semi-opaque dark slate backdrop across right half / bottom panel
    fill_rect(buf, 8, 24, 624, 464, 0xFF0C_1018);
    draw_rect_outline(buf, 8, 24, 624, 464, 0xFF3E_8EDE);

    let status = if paused { "PAUSED" } else { "RUNNING" };
    let header = format!(
        "LLE DEBUGGER | {} | {} | [{}] [F1:Run F2:Step F3:Frm F10:Cls]",
        cpu.arch, sys_name, status
    );
    fill_rect(buf, 9, 25, 622, 16, 0xFF1A_2638);
    draw_string(buf, 14, 29, &header, 0xFFFF_D166);

    let sub = format!(
        "Media: {} | Cycles: {} | Halted: {} | PC:{:06X} SP:{:06X}",
        media_name, cpu.cycles, cpu.halted, cpu.pc, cpu.sp
    );
    draw_string(buf, 14, 46, &sub, 0xFF72_EFDD);

    // Registers panel (left top) + Live Audio Oscilloscope (left bottom)
    draw_rect_outline(buf, 14, 60, 224, 196, 0xFF2B_3D5B);
    draw_string(buf, 20, 65, "LIVE CPU REGISTERS", 0xFF4E_A8DE);
    draw_string(buf, 20, 79, &format!("FLAGS: {}", cpu.flags), 0xFFFF_B703);

    for (idx, (name, val)) in cpu.registers.iter().take(12).enumerate() {
        let col_x = if idx < 6 { 20 } else { 126 };
        let row_y = 95 + (idx % 6) as i32 * 13;
        draw_string(
            buf,
            col_x,
            row_y,
            &format!("{:<4}:{}", name, val),
            0xFFE2_E8F0,
        );
    }

    draw_string(buf, 20, 175, "LIVE AUDIO OSCILLOSCOPE", 0xFF4E_A8DE);
    draw_rect_outline(buf, 20, 187, 212, 62, 0xFF1E_2D44);
    fill_rect(buf, 21, 218, 210, 1, 0xFF1E_2D44);
    if !audio_samples.is_empty() {
        let plot_w = 208usize;
        let mid_y = 218i32;
        let mut prev_y = mid_y;
        for px in 0..plot_w {
            let s_idx = (px * audio_samples.len()) / plot_w;
            let sample = audio_samples[s_idx] as i32;
            let y = (mid_y - (sample * 27) / 32_768).clamp(189, 247);
            let y_lo = prev_y.min(y);
            let y_hi = prev_y.max(y);
            fill_rect(buf, 22 + px as i32, y_lo, 1, (y_hi - y_lo) + 1, 0xFF06_D6A0);
            prev_y = y;
        }
    } else {
        draw_string(buf, 82, 214, "(silent)", 0xFF64_748B);
    }

    // Disassembly panel (right)
    draw_rect_outline(buf, 246, 60, 380, 196, 0xFF2B_3D5B);
    draw_string(buf, 252, 65, "LIVE DISASSEMBLY (@ PC)", 0xFF4E_A8DE);
    for (idx, insn) in disasm.iter().take(13).enumerate() {
        let row_y = 81 + idx as i32 * 13;
        let is_pc = insn.address == cpu.pc;
        if is_pc {
            fill_rect(buf, 248, row_y - 1, 376, 11, 0xFF22_3A5E);
        }
        let hex_bytes: String = insn
            .bytes
            .iter()
            .take(4)
            .map(|b| format!("{b:02X}"))
            .collect::<Vec<_>>()
            .join(" ");
        let line = format!(
            "{}{:05X}: {:<11} {}",
            if is_pc { ">" } else { " " },
            insn.address,
            hex_bytes,
            insn.mnemonic
        );
        draw_string(
            buf,
            252,
            row_y,
            &line,
            if is_pc { 0xFFFF_D166 } else { 0xFFCB_D5E1 },
        );
    }

    // Memory Hex/ASCII Viewer (bottom)
    draw_rect_outline(buf, 14, 264, 612, 218, 0xFF2B_3D5B);
    draw_string(
        buf,
        20,
        269,
        &format!(
            "MEMORY INSPECTOR (Base: {:06X}) [Up/Dn:+/-16B PgUp/Dn:+/-256B Home/End]",
            mem_base
        ),
        0xFF4E_A8DE,
    );

    for row in 0..14 {
        let offset = row * 16;
        if offset >= mem_bytes.len() {
            break;
        }
        let slice = &mem_bytes[offset..(offset + 16).min(mem_bytes.len())];
        let mut hex = String::with_capacity(48);
        let mut ascii = String::with_capacity(16);
        for (i, &b) in slice.iter().enumerate() {
            if i == 8 {
                hex.push(' ');
            }
            hex.push_str(&format!("{b:02X} "));
            ascii.push(if (0x20..=0x7E).contains(&b) {
                b as char
            } else {
                '.'
            });
        }
        let row_y = 285 + row as i32 * 13;
        let line = format!(
            "{:06X}: {:<49} |{}|",
            mem_base.wrapping_add(offset as u32),
            hex,
            ascii
        );
        draw_string(buf, 20, row_y, &line, 0xFF94_A3B8);
    }
}

