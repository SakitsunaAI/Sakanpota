void GUIFont::drawChar(uint32* buffer, int pitch, int x, int y, char c, uint32 fg, uint32 bg) {
    if (c < 32 || c > 126) c = ' ';
    const uint8* glyph = font8x8[c - 32];
    int stride = (pitch <= 640) ? pitch : (pitch / 4);

    for (int row = 0; row < 8; row++) {
        uint8 dots = glyph[row];
        for (int col = 0; col < 8; col++) {
            int px = x + col;
            int py = y + row;
            if (px >= 0 && px < 640 && py >= 0 && py < 512) {
                if (dots & (0x80 >> col)) {
                    buffer[py * stride + px] = fg;
                } else if ((bg & 0xFF000000) != 0) {
                    buffer[py * stride + px] = bg;
                }
            }
        }
    }
}

void GUIFont::drawString(uint32* buffer, int pitch, int x, int y, const std::string& text, uint32 fg, uint32 bg) {
    int curX = x;
    for (char c : text) {
        if (c == '\n') {
            y += 9;
            curX = x;
            continue;
        }
        drawChar(buffer, pitch, curX, y, c, fg, bg);
        curX += 8;
    }
}

void GUIFont::fillRect(uint32* buffer, int pitch, int x, int y, int w, int h, uint32 color) {
    int stride = (pitch <= 640) ? pitch : (pitch / 4);
    int x1 = std::max(0, x);
    int y1 = std::max(0, y);
    int x2 = std::min(640, x + w);
    int y2 = std::min(512, y + h);

    for (int py = y1; py < y2; py++) {
        for (int px = x1; px < x2; px++) {
            buffer[py * stride + px] = color;
        }
    }
}

void GUIFont::drawRect(uint32* buffer, int pitch, int x, int y, int w, int h, uint32 color) {
    int stride = (pitch <= 640) ? pitch : (pitch / 4);
    for (int px = x; px < x + w; px++) {
        if (px >= 0 && px < 640) {
            if (y >= 0 && y < 512) buffer[y * stride + px] = color;
            if (y + h - 1 >= 0 && y + h - 1 < 512) buffer[(y + h - 1) * stride + px] = color;
        }
    }
    for (int py = y; py < y + h; py++) {
        if (py >= 0 && py < 512) {
            if (x >= 0 && x < 640) buffer[py * stride + x] = color;
            if (x + w - 1 >= 0 && x + w - 1 < 640) buffer[py * stride + (x + w - 1)] = color;
        }
    }
}

uint8 GUIFont::getGlyphRow(char c, int row) {
    if (row < 0 || row >= 8) return 0;
    if (c >= 32 && c <= 126) {
        return font8x8[c - 32][row];
    }
    return 0;
}

