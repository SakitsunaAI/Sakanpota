SAA5050::SAA5050() {}

void SAA5050::renderScreen(const uint8* ram7C00, uint32* framebuffer, int pitch, bool flashState) {
    // 40 columns x 25 rows
    for (int row = 0; row < ROWS; row++) {
        uint8 fgColor = 7; // Default White
        uint8 bgColor = 0; // Default Black
        bool graphicsMode = false;
        bool separated = false;
        bool flash = false;
        bool doubleHeight = false;

        for (int col = 0; col < COLS; col++) {
            uint8 code = ram7C00[row * COLS + col] & 0x7F;

            // Handle control codes
            if (code < 32) {
                if (code >= 1 && code <= 7) {
                    fgColor = code;
                    graphicsMode = false;
                } else if (code == 8) {
                    flash = true;
                } else if (code == 9) {
                    flash = false;
                } else if (code == 12) {
                    doubleHeight = false;
                } else if (code == 13) {
                    doubleHeight = true;
                } else if (code >= 17 && code <= 23) {
                    fgColor = code - 16;
                    graphicsMode = true;
                } else if (code == 25) {
                    separated = false;
                } else if (code == 26) {
                    separated = true;
                } else if (code == 28) {
                    bgColor = 0; // Black background
                } else if (code == 29) {
                    bgColor = fgColor; // New background
                }
                code = 32; // Control codes display as space
            }

            uint32 fg = teletextPalette[fgColor];
            uint32 bg = teletextPalette[bgColor];

            if (flash && flashState) {
                fg = bg; // Flashing text becomes background color
            }

            // Target rectangle for this character cell (16 wide x 20 high)
            int destX = col * CHAR_WIDTH;
            int destY = row * CHAR_HEIGHT;

            if (graphicsMode && code >= 32) {
                // 6-cell mosaic graphics: 2 columns x 3 sub-blocks
                // sub0: bit 0, sub1: bit 1
                // sub2: bit 2, sub3: bit 3
                // sub4: bit 4, sub5: bit 6
                bool sub[6];
                sub[0] = (code & 0x01) != 0;
                sub[1] = (code & 0x02) != 0;
                sub[2] = (code & 0x04) != 0;
                sub[3] = (code & 0x08) != 0;
                sub[4] = (code & 0x10) != 0;
                sub[5] = (code & 0x40) != 0;

                for (int py = 0; py < CHAR_HEIGHT; py++) {
                    int subY = (py < 6) ? 0 : ((py < 13) ? 1 : 2);
                    uint32* linePtr = framebuffer + (destY + py) * (pitch / 4) + destX;
                    for (int px = 0; px < CHAR_WIDTH; px++) {
                        int subX = (px < CHAR_WIDTH / 2) ? 0 : 1;
                        int idx = subY * 2 + subX;
                        bool on = sub[idx];

                        if (separated) {
                            // Separated graphics gap
                            if (px == 0 || px == (CHAR_WIDTH / 2) - 1 || px == (CHAR_WIDTH / 2) || px == CHAR_WIDTH - 1 ||
                                py == 0 || py == 5 || py == 6 || py == 12 || py == 13 || py == CHAR_HEIGHT - 1) {
                                on = false;
                            }
                        }
                        linePtr[px] = on ? fg : bg;
                    }
                }
            } else {
                // Alphanumeric character from fontData (32..127)
                int fontIdx = (code >= 32 && code <= 127) ? (code - 32) : 0;
                const uint8* glyph = fontData[fontIdx];

                for (int scanline = 0; scanline < 10; scanline++) {
                    uint8 dots = glyph[scanline];
                    // Render 2 vertical pixels for each of the 10 font scanlines = 20 pixels total
                    for (int dy = 0; dy < 2; dy++) {
                        uint32* linePtr = framebuffer + (destY + scanline * 2 + dy) * (pitch / 4) + destX;
                        // 6 dots centered in 16 pixels: 2px left margin, each dot 2px wide, 2px right margin
                        for (int px = 0; px < CHAR_WIDTH; px++) {
                            bool lit = false;
                            if (px >= 2 && px < 14) {
                                int dotCol = (px - 2) / 2;
                                lit = (dots & (0x20 >> dotCol)) != 0;
                            }
                            linePtr[px] = lit ? fg : bg;
                        }
                    }
                }
            }
        }
    }
}
